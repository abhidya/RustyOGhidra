"""Gate-emitted dispatch companion (design G2/H3: address-keyed uniform ABI).

The ROM is dispatch-table-driven: stored function pointers in game data are
GameCube 0x80xxxxxx CODE addresses sitting in the shared linear memory, and a
composed wasm module has no way to call them (docs/playable-port-design.md,
section V3 G2). The normative mechanism (V4 H3, upheld by the V5 verdict) is a
UNIFORM DISPATCH ABI: link-time adapter thunks with ONE canonical signature,
an address-keyed registration table, and a defined miss-handler import that
routes unknown addresses to the host bridge -- a miss is a bridge call, never
a trap and never undefined behavior.

This module is the derivation half of that mechanism. At window link time the
assembly gate (src/port_assembly_gate.py) asks it to:

  1. derive, for every function DEFINED in the window's units, the callee's
     GC address and marshalling signature (from the unit's own chunk markers
     and definition heads -- the authoritative in-artifact evidence -- with
     zz_/FUN_ name encoding and the owner registry as fallbacks);
  2. emit a companion C translation unit containing one adapter thunk per
     defined function (canonical signature `int __gf_thunk_<addr>(int)`), the
     address-keyed table, the `__gf_dispatch` lookup entry point, and the
     declared `__gf_dispatch_miss` import; plus the frame-ABI header the
     thunks marshal through.

Everything here is DERIVED, never hand-edited, and fails closed: a defined
function whose address or signature cannot be derived is a companion problem
the gate turns into a loud `dispatch_companion_failed` refusal -- never a
silent skip (a defined function silently routed to the miss handler would be
a wrong-behavior bridge call, not a defined miss).

Import-light on purpose: only src.port_assembly_abi, whose
`dispatch_value_class` / `symbol_gc_address` are the single-source machinery
for wasm value classes and name-encoded addresses.
"""

